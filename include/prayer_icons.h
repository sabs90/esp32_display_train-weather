// Helper function to get icon for prayer
const unsigned char* getPrayerIcon(const String& prayerName, bool inverted = false) {
    if (prayerName == "Fajr") return epd_bitmap_fajr;
    if (prayerName == "Sunrise") return epd_bitmap_sunrise;
    if (prayerName == "Dhuhr") return epd_bitmap_dhuhr;
    if (prayerName == "Asr") return epd_bitmap_asr;
    if (prayerName == "Maghrib") return epd_bitmap_maghrib;
    if (prayerName == "Isha") return epd_bitmap_isha;
    return epd_bitmap_fajr; // Default fallback
}

